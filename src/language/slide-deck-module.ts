import {
    createDefaultModule, createDefaultSharedModule, DefaultSharedModuleContext, inject,
    LangiumServices, LangiumSharedServices, Module, PartialLangiumServices, DefaultTokenBuilder
} from 'langium';
import { SlideDeckGeneratedModule, SlideDeckGeneratedSharedModule } from './generated/module';

/**
 * Custom TokenBuilder that prioritizes specific terminals
 */
class SlideDeckTokenBuilder extends DefaultTokenBuilder {
    protected override buildTerminalTokens(grammar: any) {
        const tokens = super.buildTerminalTokens(grammar);
        
        // Find the paragraph text token and mark it as longer_alt
        const paragraphToken = tokens.find((t: any) => t.name === 'PARAGRAPH_TEXT');
        if (paragraphToken) {
            // Mark all other tokens as having higher priority than PARAGRAPH_TEXT
            paragraphToken.LONGER_ALT = tokens.filter((t: any) =>
                t.name === 'HEADER_LEVEL' ||
                t.name === 'LIST_MARKER' ||
                t.name === '>' ||
                t.name === 'MEDIA_LINE' ||
                t.name === 'CODE_BLOCK' ||
                t.name === 'NESTED_STYLE_DELIMITER' ||  // Must be before STYLE_DELIMITER
                t.name === 'STYLE_END' ||
                t.name === 'STYLE_DELIMITER' ||
                t.name === 'STYLE_ATTRS' ||
                t.name === 'TRANSITION_ATTR' ||
                t.name === 'FRAGMENT_ATTRS' ||
                t.name === 'SYNC_DELIMITER_KEEP' ||
                t.name === 'SYNC_DELIMITER' ||
                t.name === 'FRAGMENT_SEPARATOR' ||
                t.name === 'SLIDE_SEPARATOR' ||
                // Include keyword tokens for metadata
                t.name === '{' || t.name === '}' || t.name === ':' ||
                t.name === 'author' || t.name === 'title'||
                t.name === 'logo' || t.name === 'transition' || t.name === 'chalkboard' ||
                t.name === 'chalkboard-theme' || t.name === 'chalkboard-boardmarker-width' ||
                t.name === 'chalkboard-chalk-width' || t.name === 'chalkboard-chalk-effect' ||
                t.name === 'chalkboard-src' || t.name === 'chalkboard-readonly' ||
                t.name === 'chalkboard-buttons' || t.name === 'chalkboard-transition'
            );
        }

        return tokens;
    }
}

/**
 * Declaration of custom services - add your own service classes here.
 */
export type SlideDeckAddedServices = {
    validation: {}
}

/**
 * Union of Langium default services and your custom services - use this as constructor parameter
 * of custom service classes.
 */
export type SlideDeckServices = LangiumServices & SlideDeckAddedServices;

/**
 * Dependency injection module that overrides Langium default services and contributes the
 * declared custom services. The Langium defaults can be partially specified to override only
 * selected services, while the custom services must be fully specified.
 */
export const SlideDeckModule: Module<
    SlideDeckServices,
    PartialLangiumServices & SlideDeckAddedServices
> = {
    validation: {},
    parser: {
        TokenBuilder: () => new SlideDeckTokenBuilder(),
    },
};

/**
 * Create the full set of services required by Langium.
 *
 * First inject the shared services by merging two modules:
 *  - Langium default shared services
 *  - Services generated by langium-cli
 *
 * Then inject the language-specific services by merging three modules:
 *  - Langium default language-specific services
 *  - Services generated by langium-cli
 *  - Services specified in this file
 *
 * @param context Optional module context with the LSP connection
 * @returns An object wrapping the shared services and the language-specific services
 */
export function createSlideDeckServices(
    context: DefaultSharedModuleContext
): {
    shared: LangiumSharedServices
    SlideDeck: SlideDeckServices
} {
    const shared = inject(
        createDefaultSharedModule(context),
        SlideDeckGeneratedSharedModule
    )
    const SlideDeck = inject(
        createDefaultModule({ shared }),
        SlideDeckGeneratedModule,
        SlideDeckModule
    )
    shared.ServiceRegistry.register(SlideDeck)
    return { shared, SlideDeck }
}
